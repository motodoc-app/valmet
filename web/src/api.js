// API client. Uses the FastAPI backend when it is running (dev / local demo); otherwise falls back to the
// serverless implementation in static-api.js (hosted demo). Both expose the same functions.
import { staticApi } from "./static-api.js";

const j = async (r) => { if (!r.ok) throw new Error(`${r.status} ${await r.text()}`); return r.json(); };
const post = (url, body) => fetch(url, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) }).then(j);
const unpack = (hex, n) => {
  const out = new Uint8Array(n);
  for (let i = 0; i < n; i++) out[i] = (parseInt(hex.substr((i >> 3) * 2, 2), 16) >> (7 - (i & 7))) & 1;
  return out;
};

const serverApi = {
  isStatic: false,
  llmDown: false,                    // set from the last diagnosis / free question: did the live LLM answer?
  health: () => fetch("/api/health").then(j),
  scene: () => fetch("/api/scene").then(j),
  grid: async () => { const g = await fetch("/api/nav/grid").then(j); const n = g.W * g.H; return { ...g, walkableMask: unpack(g.walkable, n), occupiedMask: unpack(g.occupied, n) }; },
  plan: (body) => post("/api/nav/plan", body),
  async diagnose(id) {
    const d = await fetch(`/api/diagnose/${id}`).then(j);
    // live AI unavailable: show the narrative pre-generated (and citation-checked) at export time instead of the raw
    // template wording, labelled as such; the evidence, confidence and steps stay the live server's
    serverApi.llmDown = !/^llm:/.test(d.narrative?.mode || "");
    if (/^template/.test(d.narrative?.mode || "")) {
      try { const s = await staticApi.diagnose(id); if (/^llm:/.test(s.narrative?.mode || "")) return { ...d, narrative: { ...s.narrative, fallback: d.narrative.mode } }; } catch { /* keep the template */ }
    }
    return d;
  },
  async command(text, selected, history = []) {
    const r = await post("/api/copilot/command", { text, selected_asset_id: selected, history });
    // live AI unavailable (no key, no quota, no network): use the pre-generated answer to a similar question instead
    // of plain document search, labelled as such (copilot-ui shows "live AI unavailable")
    if (r.intent === "question") serverApi.llmDown = !/^llm:/.test(r.mode || "");
    if (r.intent === "question" && /^(retrieval-only|template)/.test(r.mode || "")) {
      try { const f = await staticApi.answer(text, r.asset_id || selected, history); if (f.mode === "faq") return { ...r, ...f, actions: r.actions, fallback: r.mode }; } catch { /* keep the server answer */ }
    }
    return r;
  },
  query: (question, asset_id, component) => post("/api/copilot/query", { question, asset_id, component }),
  search: (q) => fetch(`/api/knowledge/search?q=${encodeURIComponent(q || "pump fouling flow current")}`).then(j),
  doc: (id) => fetch(`/api/knowledge/doc/${encodeURIComponent(id)}`).then(j),
  xrayModel: () => fetch("/api/xray/model").then(j),
  draftWO: (asset_id) => post("/api/work-orders/draft", { asset_id }),
};

export let api = staticApi;
export async function connect() {
  try {
    const ctl = new AbortController();
    const t = setTimeout(() => ctl.abort(), 1500);
    const r = await fetch("/api/health", { signal: ctl.signal });
    clearTimeout(t);
    if (r.ok && (r.headers.get("content-type") || "").includes("json")) api = serverApi;
  } catch { /* hosted demo: no server */ }
  return api;
}

// Scan to render, for both modes: the streaming chunks listed in static/scan.json (generated by the web build),
// or the committed data/scene.splat when the chunk manifest is missing. loadScan() also falls back per chunk.
export const SCAN_FALLBACK = { splat_format: "splat", chunks: [{ url: "./data/scene.splat" }], fallback: true };
// Full-fidelity scan (static/hq/scan-hq.json: every splat, SH, SPZ chunks; built by scripts/build-hq-scan.mjs) is
// the default; it carries the classic manifest as `.classic` so Facility.loadScan can fall back to it.
// ?render=classic forces the classic (xq16 / scene.splat) path.
export const RENDER = new URLSearchParams(location.search).get("render") === "classic" ? "classic" : "hq";
export async function scanManifest() {
  const classic = classicManifest();
  if (RENDER === "classic") return classic;
  try {
    const r = await fetch("./static/hq/scan-hq.json");
    if (!r.ok || !(r.headers.get("content-type") || "").includes("json")) return classic;
    const m = await r.json();
    if (m.splat_format !== "spz" || !m.chunks?.length || m.transform?.length !== 16) return classic;
    return { ...m, chunks: m.chunks.map((c) => ({ ...c, url: `./static/hq/${c.file}` })), classic: await classic };
  } catch { return classic; }
}
async function classicManifest() {
  try {
    const r = await fetch("./static/scan.json");
    if (!r.ok || !(r.headers.get("content-type") || "").includes("json")) return SCAN_FALLBACK;
    const m = await r.json();
    if (!m.chunks?.length) return SCAN_FALLBACK;
    return { ...m, chunks: m.chunks.map((c) => ({ ...c, url: `./static/${c.file}` })) };
  } catch { return SCAN_FALLBACK; }
}
