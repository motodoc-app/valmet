// "Ask about the plant" conversation panel, shared by the 3D app (main.js) and the 2D floor plan (plan2d.js).
// Shows the conversation as question/answer bubbles, how each answer was made (Live AI / Pre-generated / Document
// search / Rule-based), clickable citations (the app's global .cite handler opens the document), three follow-up
// chips that fit the last answer and suggestions for the selected asset. The host app runs the actions
// (select, fly to, dispatch, X-Ray, diagnosis, ...) through `run(response)`.
import { icon } from "./icons.js";
import { esc, cites } from "./ui.js";
import { detectIntent } from "./faq-match.js";
import "./copilot-ui.css";

const MAX_TURNS = 12;               // kept on screen
const MEMORY = 3;                   // turns sent back to the copilot for follow-ups

/** How the answer was produced, in words a judge can check. */
export function modeLabel(r, isStatic) {
  const m = String(r?.mode || "");
  if (m === "faq") return { cls: "pre", text: `Pre-generated answer to a similar question: “${r.matched_q}” (offline demo)` };
  if (m === "docsearch") return { cls: "doc", text: "Document search: composed from the top sources (offline demo, no live AI)" };
  if (m.startsWith("llm:")) return isStatic
    ? { cls: "pre", text: `Pre-generated by ${m.slice(4)} at export time, citations checked (offline demo)` }
    : { cls: "live", text: `Live AI · ${m.slice(4)} · citations checked` };
  if (m.startsWith("retrieval") || m.startsWith("template")) return { cls: "doc", text: "Document search (live AI unavailable)" };
  return { cls: "rule", text: "Rule-based command · workbook data" };
}

const plain = (s) => String(s || "").replace(/\*\*/g, "").replace(/\s+/g, " ").trim();
// [ASSET-017] opens the asset card (DOC-ASSET-017), which is a real document; the visible ID stays the same
const body = (text) => String(text || "").replace(/\*\*/g, "").split(/\n+/).map((p) => p.trim()).filter(Boolean)
  .map((p) => `<p>${cites(p.replace(/^[-•]\s*/, "• ")).replace(/data-doc="ASSET-(\d{3})"/g, 'data-doc="DOC-ASSET-$1"')}</p>`).join("");

export function createCopilot({ pop, input, api, selected, assetById, run }) {
  const turns = [];
  let busy = false;
  const isStatic = () => !!api()?.isStatic;
  const sel = () => selected() || null;

  function suggestions() {
    const a = sel(), out = [];
    if (a) {
      const faulty = a.condition_state && a.condition_state !== "healthy";
      out.push(faulty ? `What's wrong with ${a.tag}?` : `What is the status of ${a.tag}?`);
      if (faulty) out.push(`What should I check first on ${a.tag}?`, `Is ${a.tag} safe to keep running?`, `Which parts of ${a.tag} are suspect?`);
      else out.push(`What is the maintenance history of ${a.tag}?`);
      out.push(`Send the robot to ${a.tag}`);
    }
    out.push("Which assets need attention first?", "Where is the faulty pump?", "Which motor is overheating?", "How were the objects in the scan labelled?",
      "What data is real and what is synthetic?", "Show me the relevant manual", "Can I practise inspecting this equipment?");
    return out.slice(0, a ? 8 : 7);
  }

  /** Three chips that continue the conversation from the last answer. */
  function followups(t) {
    const r = t.r || {}, acts = (r.actions || []).map((x) => x.type);
    const a = assetById(r.asset_id) || (r.intent === "question" ? null : sel());
    const asked = detectIntent(t.q);
    if (a && a.tag) {
      const faulty = a.condition_state !== "healthy";
      const pool = [
        ["check", "What should I check first?", `What should I check first on ${a.tag}?`],
        ["parts", "Show the suspect parts", `Which parts of ${a.tag} are suspect?`, faulty && !acts.includes("xray")],
        ["navigate", `Send the robot to ${a.tag}`, `Send the robot to ${a.tag}`, !acts.includes("navigate")],
        ["safe", "Is it safe to keep running?", `Is ${a.tag} safe to keep running?`, faulty],
        ["evidence", "What evidence supports this?", `What evidence supports the ${a.tag} diagnosis?`, faulty],
        ["history", "Maintenance history", `What is the maintenance history of ${a.tag}?`],
        ["wrong", `What's wrong with ${a.tag}?`, `What's wrong with ${a.tag}?`, faulty],
      ].filter(([k, , , okay = true]) => okay && k !== asked && !(k === "parts" && /suspect/i.test(t.q)) && !(k === "navigate" && /send|dispatch/i.test(t.q)));
      return pool.slice(0, 3).map(([, label, q]) => ({ label, q }));
    }
    return ["Which assets need attention first?", "Which motor is overheating?", "How does the robot plan routes?", "What data is real and what is synthetic?", "What would a pilot measure?"]
      .filter((q) => q.toLowerCase() !== t.q.toLowerCase()).slice(0, 3).map((q) => ({ label: q, q }));
  }

  function render() {
    const head = `<div class="cp-head"><span class="cp-title">${icon("spark")}Copilot<span class="cp-run ${isStatic() ? "off" : "on"}">${isStatic() ? "Offline demo" : "Live AI"}</span></span>
      <span class="cp-tools">${turns.length ? '<button class="link" data-cp-clear title="Start a new conversation">New</button>' : ""}<button class="link" data-pop-close aria-label="Close">${icon("close")}</button></span></div>`;
    if (!turns.length) {
      pop.innerHTML = `${head}<div class="cp-intro">Ask about an asset, the room or how this prototype works. Answers cite their sources; tap an ID to open it.</div>
        <div class="cp-sugg">${suggestions().map((s) => `<button class="sugg" data-q="${esc(s)}">${icon("search")}${esc(s)}</button>`).join("")}</div>
        <div class="cp-foot">Synthetic builder-pack data · decision support only, no plant control</div>`;
      return;
    }
    const conv = turns.map((t, i) => {
      const last = i === turns.length - 1;
      let a;
      if (!t.r) a = `<div class="cp-a pending"><span class="cp-dots"><i></i><i></i><i></i></span>Working…</div>`;
      else if (t.err) a = `<div class="cp-a err">Something went wrong: ${esc(t.err)}</div>`;
      else {
        const ml = modeLabel(t.r, isStatic());
        const fu = last ? followups(t) : [];
        a = `<div class="cp-a${last ? " last" : ""}">${body(t.r.text)}</div>
          <div class="cp-mode ${ml.cls}">${esc(ml.text)}</div>
          ${fu.length ? `<div class="cp-fu">${fu.map((f) => `<button class="chip" data-q="${esc(f.q)}" title="${esc(f.q)}">${esc(f.label)}</button>`).join("")}</div>` : ""}`;
      }
      return `<div class="cp-turn${last ? " cp-last" : ""}"><div class="cp-q">${esc(t.q)}</div>${a}</div>`;
    }).join("");
    pop.innerHTML = `${head}<div class="cp-conv">${conv}</div><div class="cp-foot">Synthetic builder-pack data · decision support only, no plant control</div>`;
    const c = pop.querySelector(".cp-conv"), lastQ = pop.querySelector(".cp-last");
    if (c && lastQ) c.scrollTop = Math.max(0, lastQ.offsetTop - c.offsetTop - 4);
  }

  const show = () => { render(); pop.classList.remove("hidden"); };
  const hide = () => pop.classList.add("hidden");

  async function ask(q) {
    q = String(q || "").trim();
    if (!q || busy) return;
    busy = true;
    input.value = "";
    const history = turns.filter((t) => t.r && !t.err).slice(-MEMORY)
      .map((t) => ({ q: t.q, a: plain(t.r.text).slice(0, 700), asset_id: t.r.asset_id || null }));
    const t = { q, r: null };
    turns.push(t);
    if (turns.length > MAX_TURNS) turns.shift();
    pop.dataset.answer = "1";
    show();
    try {
      t.r = await api().command(q, sel()?.asset_id, history);
      render();
      await run(t.r);
    } catch (e) { t.r = { text: "" }; t.err = e.message || String(e); }
    busy = false;
    render();                         // follow-ups use the new selection
    return t.r;
  }

  input.addEventListener("focus", show);
  input.addEventListener("keydown", (e) => {
    if (e.key === "Enter") ask(input.value);
    if (e.key === "Escape") { hide(); input.blur(); }
  });
  pop.addEventListener("click", (e) => {
    const s = e.target.closest("[data-q]"); if (s) { ask(s.dataset.q); return; }
    if (e.target.closest("[data-cp-clear]")) { turns.length = 0; delete pop.dataset.answer; render(); input.focus(); return; }
    if (e.target.closest("[data-pop-close]")) hide();
  });
  document.addEventListener("pointerdown", (e) => { if (!e.target.closest(".ask") && !e.target.closest("#sheet")) hide(); });
  return { ask, show, hide, turns, render };
}
